export const PIXEL_FONTS = Object.freeze({
    '5x7': { glyphs: G5, h: 7, spacing: 1 },
    '3x5': { glyphs: G3, h: 5, spacing: 1 },
});

const ALIASES = { x: '×', X: '×', '*': '×' };

function glyphFor(font, ch) {
    const g = font.glyphs;
    if (g[ch]) return g[ch];
    if (ch === 'x' || ch === '*') return g['×'];
    const up = ch.toUpperCase();
    if (g[up]) return g[up];
    return null;
}

let _missing = 0;
export function getPixelFontMissingCount() { return _missing; }

/** 文本像素宽度（未缩放） */
export function measurePixelText(text, fontName = '5x7') {
    const font = PIXEL_FONTS[fontName] || PIXEL_FONTS['5x7'];
    let w = 0;
    const s = String(text);
    for (let i = 0; i < s.length; i++) {
        const g = glyphFor(font, s[i]) || font.glyphs[' '];
        w += g[0].length + (i < s.length - 1 ? font.spacing : 0);
    }
    return { w, h: font.h };
}

const _cache = new Map();
const CACHE_MAX = 600;

function makeCanvas(w, h) {
    if (typeof OffscreenCanvas !== 'undefined') return new OffscreenCanvas(w, h);
    const c = document.createElement('canvas');
    c.width = w;
    c.height = h;
    return c;
}

/**
 * 把文本栅格化成画布（带可选 1px 描边 / 底部投影），结果缓存。
 * @param {string} text
 * @param {{font?:string,color?:string,outline?:string|null,shadow?:string|null}} [o]
 */
export function getPixelTextCanvas(text, o = {}) {
    const fontName = o.font || '5x7';
    const color = o.color || '#ffffff';
    const outline = o.outline === undefined ? INK : o.outline;
    const shadow = o.shadow || null;
    const key = `${fontName}|${color}|${outline}|${shadow}|${text}`;
    let c = _cache.get(key);
    if (c) {
        _cache.delete(key);
        _cache.set(key, c);
        return c;
    }
    const font = PIXEL_FONTS[fontName] || PIXEL_FONTS['5x7'];
    const { w, h } = measurePixelText(text, fontName);
    const pad = outline ? 1 : 0;
    const extraB = shadow ? 1 : 0;
    const W = w + pad * 2;
    const H = h + pad * 2 + extraB;
    c = makeCanvas(Math.max(1, W), Math.max(1, H));
    const g = c.getContext('2d');
    // 先收集实心像素
    const solid = new Uint8Array(W * H);
    let x = pad;
    const s = String(text);
    for (let i = 0; i < s.length; i++) {
        let rows = glyphFor(font, s[i]);
        if (!rows) { _missing++; rows = font.glyphs[' ']; }
        for (let r = 0; r < rows.length; r++) {
            const row = rows[r];
            for (let cx = 0; cx < row.length; cx++) {
                if (row[cx] === '#') solid[(r + pad) * W + (x + cx)] = 1;
            }
        }
        x += rows[0].length + font.spacing;
    }
    if (shadow) {
        g.fillStyle = shadow;
        for (let p = 0; p < solid.length; p++) {
            if (!solid[p]) continue;
            const py = ((p / W) | 0) + 1;
            if (py < H) g.fillRect(p % W, py + (outline ? 1 : 0), 1, 1);
        }
    }
    if (outline) {
        g.fillStyle = outline;
        for (let p = 0; p < solid.length; p++) {
            if (solid[p]) continue;
            const px = p % W;
            const py = (p / W) | 0;
            // 8 邻域描边：数字在杂乱背景上需要完整外框
            let near = false;
            for (let dy = -1; dy <= 1 && !near; dy++) {
                for (let dx = -1; dx <= 1; dx++) {
                    const nx = px + dx;
                    const ny = py + dy;
                    if (nx >= 0 && ny >= 0 && nx < W && ny < H && solid[ny * W + nx]) { near = true; break; }
                }
            }
            if (near) g.fillRect(px, py, 1, 1);
        }
    }
    g.fillStyle = color;
    for (let p = 0; p < solid.length; p++) {
        if (solid[p]) g.fillRect(p % W, (p / W) | 0, 1, 1);
    }
    _cache.set(key, c);
    if (_cache.size > CACHE_MAX) _cache.delete(_cache.keys().next().value);
    return c;
}

/**
 * 在当前上下文的「美术像素」网格上画文字。x/y 为逻辑坐标（会经过当前变换），
 * 字形按整数倍 scale 放大，左上角吸附到整缓冲像素。
 * align: 'left' | 'center' | 'right'；baseline: 'top' | 'middle' | 'bottom'
 */
export function drawPixelText(ctx, text, x, y, o = {}) {
    const c = getPixelTextCanvas(String(text), o);
    const scale = Math.max(1, o.scale | 0 || 1);
    const m = ctx.getTransform();
    let bx = m.a * x + m.c * y + m.e;
    let by = m.b * x + m.d * y + m.f;
    const w = c.width * scale;
    const h = c.height * scale;
    const align = o.align || 'left';
    const baseline = o.baseline || 'top';
    if (align === 'center') bx -= w / 2;
    else if (align === 'right') bx -= w;
    if (baseline === 'middle') by -= h / 2;
    else if (baseline === 'bottom') by -= h;
    ctx.save();
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.imageSmoothingEnabled = false;
    if (o.alpha != null) ctx.globalAlpha *= o.alpha;
    ctx.drawImage(c, Math.round(bx), Math.round(by), w, h);
    ctx.restore();
    return { w, h };
}
